"""Run with python -m unittest discover -s scripts -p test_transfer_db.py.

Integration tests require CAL01_TRANSFER_TEST_CONFIG (a private PostgreSQL JSON
configuration for a role with CREATEDB) and CAL01_TRANSFER_TEST_POSTGRES_BIN.
Only randomly named cal01_transfer_test_* databases are created or removed.
"""
from contextlib import redirect_stdout
import importlib.util
import io
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
import uuid
import subprocess

import psycopg
from psycopg import sql


spec = importlib.util.spec_from_file_location("transfer_db", Path(__file__).with_name("transfer-db.py"))
transfer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(transfer)


class TransferUnitTests(unittest.TestCase):
    def test_environment_connection_never_puts_password_in_command(self):
        with patch.dict(os.environ, {}, clear=True):
            result = transfer.child_environment({
                "dbname": "unit", "host": "localhost", "user": "unit", "password": "private-value",
            })
        self.assertEqual(result["PGPASSWORD"], "private-value")
        self.assertEqual(result["PGDATABASE"], "unit")
        self.assertNotIn("DATABASE_URL", result)

    def test_database_url_and_config_supported_without_exposing_password(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "config.json"
            path.write_text(json.dumps({"DATABASE_URL": "postgresql://worker:private%21@localhost:5432/shared?sslmode=require"}))
            with patch.dict(os.environ, {}, clear=True):
                actual = transfer.connection_options(path)
        self.assertEqual(actual["password"], "private!")
        self.assertEqual(actual["sslmode"], "require")

    def test_backup_inside_repository_and_existing_directory_refused(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / ".git").mkdir()
            with self.assertRaises(transfer.TransferError):
                transfer.private_directory(root / "backup")
            self.assertFalse((root / "backup").exists())
            with self.assertRaises(FileExistsError):
                transfer.private_directory(root.parent)

    def test_modified_dump_is_rejected_before_any_connection(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "database.dump").write_bytes(b"changed")
            (root / "manifest.json").write_text(json.dumps({
                "format_version": 1, "dump": {"file": "database.dump", "bytes": 7, "sha256": "bad"},
            }))
            with self.assertRaises(transfer.TransferError):
                transfer.load_backup(root)


@unittest.skipUnless(os.environ.get("CAL01_TRANSFER_TEST_CONFIG") and os.environ.get("CAL01_TRANSFER_TEST_POSTGRES_BIN"), "PostgreSQL integration environment not set")
class TransferPostgresTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.options = transfer.connection_options(os.environ["CAL01_TRANSFER_TEST_CONFIG"])
        cls.binaries = os.environ["CAL01_TRANSFER_TEST_POSTGRES_BIN"]
        cls.prefix = "cal01_transfer_test_" + uuid.uuid4().hex[:12]
        cls.source_name = cls.prefix + "_source"
        cls.target_name = cls.prefix + "_target"
        cls.failed_name = cls.prefix + "_failed"
        cls.source = dict(cls.options, dbname=cls.source_name)
        cls.target = dict(cls.options, dbname=cls.target_name)
        cls.failed = dict(cls.options, dbname=cls.failed_name)
        cls.temporary = tempfile.TemporaryDirectory(prefix="cal01-transfer-tests-")
        cls.backup = Path(cls.temporary.name) / "backup"
        with psycopg.connect(**dict(cls.options, dbname="postgres"), autocommit=True) as connection:
            for name in (cls.source_name, cls.target_name, cls.failed_name):
                connection.execute(sql.SQL("CREATE DATABASE {} TEMPLATE template0").format(sql.Identifier(name)))
        with psycopg.connect(**cls.source) as connection:
            connection.execute("CREATE TABLE auth_user (id integer PRIMARY KEY, username text, password text, is_active boolean)")
            connection.execute("CREATE TABLE django_session (session_key varchar(40) PRIMARY KEY, session_data text, expire_date timestamptz)")
            connection.execute("CREATE TABLE monitor_records (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value double precision, details jsonb, recorded_at timestamp, raw text)")
            connection.execute("INSERT INTO auth_user VALUES (7,'example','private-password-hash',true)")
            connection.execute("INSERT INTO django_session VALUES ('private-session-key','private-session-data','2026-10-24T12:00:00+09:00')")
            connection.execute("INSERT INTO monitor_records (value,details,recorded_at,raw) VALUES (0,'{\"LABEL\":1}','2024-01-02 03:36:00.123456','한글'),(1.15e-10,'{\"LABEL\":null}',NULL,''),(NULL,'{}','2024-01-02 03:36:01','원본')")
        with redirect_stdout(io.StringIO()):
            cls.manifest = transfer.export_database(cls.source, cls.backup, cls.binaries)
            dump, manifest = transfer.load_backup(cls.backup)
            transfer.restore_database(cls.target, dump, manifest, cls.target_name, cls.binaries)

    @classmethod
    def tearDownClass(cls):
        with psycopg.connect(**dict(cls.options, dbname="postgres"), autocommit=True) as connection:
            for name in (cls.source_name, cls.target_name, cls.failed_name):
                if not name.startswith(cls.prefix + "_"):
                    raise RuntimeError("Unexpected test database name")
                connection.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))
        cls.temporary.cleanup()

    def test_round_trip_preserves_accounts_rows_precision_and_sequence(self):
        with psycopg.connect(**self.source) as source, psycopg.connect(**self.target) as target:
            for table in ("auth_user", "django_session", "monitor_records"):
                statement = sql.SQL("SELECT * FROM {} ORDER BY 1").format(sql.Identifier(table))
                self.assertEqual(source.execute(statement).fetchall(), target.execute(statement).fetchall())
            for connection in (source, target):
                self.assertEqual(connection.execute("SELECT last_value,is_called FROM monitor_records_id_seq").fetchone(), (3, True))
        manifest_text = json.dumps(self.manifest)
        for secret in ("private-password-hash", "private-session-key", "private-session-data"):
            self.assertNotIn(secret, manifest_text)
        self.assertNotIn("password", self.manifest["tables"]["public.auth_user"]["hashed_columns"])

    def test_existing_database_refused_without_changes(self):
        with psycopg.connect(**self.target) as connection:
            with self.assertRaises(transfer.TransferError):
                transfer.assert_empty_database(connection, self.target_name)
            self.assertEqual(connection.execute("SELECT count(*) FROM monitor_records").fetchone()[0], 3)

    def test_wrong_confirmation_and_other_connections_refused(self):
        with psycopg.connect(**self.failed) as connection:
            with self.assertRaises(transfer.TransferError):
                transfer.assert_empty_database(connection, self.source_name)
            with psycopg.connect(**self.failed):
                with self.assertRaises(transfer.TransferError):
                    transfer.assert_empty_database(connection, self.failed_name)

    def test_changed_value_with_same_count_is_detected(self):
        with psycopg.connect(**self.target) as connection:
            connection.execute("UPDATE monitor_records SET raw='changed' WHERE id=1")
        try:
            with self.assertRaises(transfer.TransferError):
                transfer.verify_database(self.target, self.manifest)
        finally:
            with psycopg.connect(**self.target) as connection:
                connection.execute("UPDATE monitor_records SET raw='한글' WHERE id=1")

    def test_restore_error_rolls_back_all_objects(self):
        executable = transfer.tool_path("pg_restore", self.binaries)
        dump, manifest = transfer.load_backup(self.backup)
        listing = subprocess.run([executable, "--list", str(dump)], capture_output=True, check=True).stdout.decode()
        lines = [line for line in listing.splitlines() if " TABLE public auth_user " not in line]
        table_list = Path(self.temporary.name) / "intentionally-incomplete-list.txt"
        table_list.write_text("\n".join(lines), encoding="utf-8")
        original = transfer.run_postgres

        def omit_required_table(command, options):
            original(command + ["--use-list=" + str(table_list)], options)

        with patch.object(transfer, "run_postgres", side_effect=omit_required_table):
            with self.assertRaises(transfer.TransferError):
                transfer.restore_database(self.failed, dump, manifest, self.failed_name, self.binaries)
        with psycopg.connect(**self.failed) as connection:
            transfer.assert_empty_database(connection, self.failed_name)

    def test_z_source_manifest_and_dump_share_snapshot(self):
        original = transfer.database_manifest

        def write_after_manifest(connection):
            result = original(connection)
            with psycopg.connect(**self.source) as writer:
                writer.execute("INSERT INTO monitor_records (raw) VALUES ('after snapshot')")
            return result

        second_backup = Path(self.temporary.name) / "snapshot-backup"
        with patch.object(transfer, "database_manifest", side_effect=write_after_manifest):
            with redirect_stdout(io.StringIO()):
                manifest = transfer.export_database(self.source, second_backup, self.binaries)
        self.assertEqual(manifest["tables"]["public.monitor_records"]["rows"], 3)
        dump, manifest = transfer.load_backup(second_backup)
        with redirect_stdout(io.StringIO()):
            transfer.restore_database(self.failed, dump, manifest, self.failed_name, self.binaries)


if __name__ == "__main__":
    unittest.main()
